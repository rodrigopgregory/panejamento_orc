CREATE TABLE IF NOT EXISTS PLAYGROUND (
      ID INT AUTO_INCREMENT PRIMARY KEY,
      USUARIO VARCHAR(200),
      NOME VARCHAR(200),
      HTML MEDIUMTEXT,
      TASK_ID VARCHAR(100),
      SHARE_TOKEN VARCHAR(64),
      CONVERSA MEDIUMTEXT,
      ATIVO VARCHAR(5) DEFAULT 'true',
      CRIADO_EM VARCHAR(19),
      ATUALIZADO_EM VARCHAR(19)
    );

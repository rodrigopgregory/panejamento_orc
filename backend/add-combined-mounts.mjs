import 'dotenv/config';
import { configureSdkMitra, createServerFunctionMitra, listServerFunctionsMitra } from 'mitra-sdk';
configureSdkMitra({ baseURL: process.env.MITRA_BASE_URL, token: process.env.MITRA_TOKEN, integrationURL: process.env.MITRA_BASE_URL_INTEGRATIONS });
const projectId = parseInt(process.env.MITRA_PROJECT_ID);

// 121 — mount do kanban/Preenchimento em 1 ida
const CICLO_COLS = "'ID',ID,'NOME',NOME,'ANO',ANO,'STATUS',STATUS,'ULTIMO_MES_REALIZADO',ULTIMO_MES_REALIZADO,'VERSAO_ATUAL',VERSAO_ATUAL,'VERSAO_CONTROLE',VERSAO_CONTROLE,'VERSAO_ORIGEM_ID',VERSAO_ORIGEM_ID,'CRIADO_EM',CRIADO_EM,'CRIADO_POR',CRIADO_POR";
const mount = `SELECT
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',os.ID,'CICLO_ID',os.CICLO_ID,'CR_ID',os.CR_ID,'GESTOR_ID',os.GESTOR_ID,'STATUS',os.STATUS,'DRIVERS_CONFIRMADOS',os.DRIVERS_CONFIRMADOS,'COMENTARIO',os.COMENTARIO,'ATUALIZADO_EM',os.ATUALIZADO_EM,'CR_CODIGO',cr.CODIGO,'CR_NOME',cr.NOME))
     FROM ORCAMENTO_STATUS os JOIN CENTRO_RESULTADO cr ON cr.ID=os.CR_ID WHERE os.CICLO_ID={{cicloId}} AND os.GESTOR_ID={{gestorId}}), JSON_ARRAY()) AS CARDS,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('CR_ID',s.CR_ID,'ORCADO',(SELECT COALESCE(SUM(VALOR),0) FROM ORCAMENTO WHERE CICLO_ID=s.CICLO_ID AND CR_ID=s.CR_ID),'REALIZADO',(SELECT COALESCE(SUM(VALOR),0) FROM REALIZADO_CONTABIL WHERE ANO={{ano}} AND CR_ID=s.CR_ID)))
     FROM ORCAMENTO_STATUS s WHERE s.CICLO_ID={{cicloId}} AND s.GESTOR_ID={{gestorId}}), JSON_ARRAY()) AS FIN,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',d.ID,'NOME',d.NOME,'DESCRICAO',d.DESCRICAO,'COR',d.COR,'ORIGEM',d.ORIGEM,'TIPO_DRIVER',d.TIPO_DRIVER,'ATIVO',d.ATIVO,'GP_ID',gp.ID))
     FROM DRIVERS d JOIN GESTOR_PACOTE gp ON gp.DRIVER_ID=d.ID WHERE gp.GESTOR_ID={{gestorId}} AND d.TIPO_DRIVER='PACOTE' AND d.ATIVO='true'), JSON_ARRAY()) AS PACOTES,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',ID,'CICLO_ID',CICLO_ID,'DRIVER_ID',DRIVER_ID,'GESTOR_ID',GESTOR_ID,'STATUS',STATUS,'DRIVERS_CONFIRMADOS',DRIVERS_CONFIRMADOS,'COMENTARIO',COMENTARIO,'ATUALIZADO_EM',ATUALIZADO_EM))
     FROM PACOTE_STATUS WHERE CICLO_ID={{cicloId}} AND GESTOR_ID={{gestorId}}), JSON_ARRAY()) AS PACOTE_STATUS,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('CR_ID',cr_id,'TOTAL',total)) FROM (
     SELECT crc.CR_ID cr_id, COUNT(DISTINCT d.NOME) total FROM CR_CONTA crc
     LEFT JOIN CONTA_DRIVER_EXCECAO cde ON cde.CR_ID=crc.CR_ID AND cde.CONTA_ID=crc.CONTA_ID AND cde.ATIVO=true
     LEFT JOIN CONTA_DRIVER cd ON cd.CONTA_ID=crc.CONTA_ID
     LEFT JOIN DRIVERS d ON d.ID=COALESCE(cde.PACOTE_ID,cd.PACOTE_ID,cde.DRIVER_ID,cd.DRIVER_ID)
     WHERE crc.CR_ID IN (SELECT CR_ID FROM ORCAMENTO_STATUS WHERE CICLO_ID={{cicloId}} AND GESTOR_ID={{gestorId}}) AND crc.ATIVO=true AND d.ID IS NOT NULL AND d.ATIVO='true'
     GROUP BY crc.CR_ID) m), JSON_ARRAY()) AS MODELOS`;

// 122 — Premissas: ciclos + contas
const prem = `SELECT
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT(${CICLO_COLS})) FROM CICLO), JSON_ARRAY()) AS CICLOS,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',ID,'CODIGO',CODIGO,'NOME',NOME)) FROM CONTA_CONTABIL), JSON_ARRAY()) AS CONTAS`;

// 123 — Versoes: versoes + gestores(com CR_IDS) + crs
const vers = `SELECT
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT(${CICLO_COLS})) FROM CICLO), JSON_ARRAY()) AS VERSOES,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',g.ID,'NOME',g.NOME,'EMAIL',g.EMAIL,'ATIVO',g.ATIVO,'CR_IDS',g.CR_IDS)) FROM (
     SELECT g.ID,g.NOME,g.EMAIL,g.ATIVO, GROUP_CONCAT(gc.CR_ID) CR_IDS FROM GESTOR g JOIN GESTOR_CR gc ON gc.GESTOR_ID=g.ID WHERE g.ATIVO='true' GROUP BY g.ID) g), JSON_ARRAY()) AS GESTORES,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',ID,'CODIGO',CODIGO,'NOME',NOME,'ATIVO',ATIVO,'EMPRESA_ID',EMPRESA_ID)) FROM CENTRO_RESULTADO WHERE ATIVO='true'), JSON_ARRAY()) AS CRS`;

for (const [name,code,description] of [
  ['hotKanbanMount', mount, 'Mount do kanban em 1 ida (CARDS,FIN,PACOTES,PACOTE_STATUS,MODELOS). Params: cicloId,gestorId,ano.'],
  ['hotPremissasBase', prem, 'Premissas: CICLOS+CONTAS em 1 ida.'],
  ['hotVersoesBase', vers, 'Versoes: VERSOES+GESTORES+CRS em 1 ida.'],
]) await createServerFunctionMitra({ projectId, name, type:'SQL', code, description });

const fns=(await listServerFunctionsMitra({projectId})).result;
for (const n of ['hotKanbanMount','hotPremissasBase','hotVersoesBase']) console.log(n,'=>',fns.find(x=>x.name===n)?.id);

import 'dotenv/config';
import { configureSdkMitra, createServerFunctionMitra, listServerFunctionsMitra } from 'mitra-sdk';
configureSdkMitra({ baseURL: process.env.MITRA_BASE_URL, token: process.env.MITRA_TOKEN, integrationURL: process.env.MITRA_BASE_URL_INTEGRATIONS });
const projectId = parseInt(process.env.MITRA_PROJECT_ID);

const REGRAS = `SELECT crc.ID, COALESCE(ex.DRIVER_ID, cd.DRIVER_ID) AS DRIVER_ID, crc.CR_ID, crc.CONTA_ID,
       cr.CODIGO AS CR_CODIGO, cr.NOME AS CR_NOME, cc.CODIGO AS CONTA_CODIGO, cc.NOME AS CONTA_NOME,
       CASE WHEN ex.DRIVER_ID IS NOT NULL AND dexc.TIPO_DRIVER != 'PACOTE' THEN ex.DRIVER_ID
            WHEN ex.DRIVER_ID IS NULL AND cd.DRIVER_ID IS NOT NULL AND dgen.TIPO_DRIVER != 'PACOTE' THEN cd.DRIVER_ID ELSE NULL END AS MODELO_ID,
       CASE WHEN ex.DRIVER_ID IS NOT NULL AND dexc.TIPO_DRIVER != 'PACOTE' THEN dexc.NOME
            WHEN ex.DRIVER_ID IS NULL AND cd.DRIVER_ID IS NOT NULL AND dgen.TIPO_DRIVER != 'PACOTE' THEN dgen.NOME ELSE NULL END AS MODELO_NOME
     FROM CR_CONTA crc
     JOIN CENTRO_RESULTADO cr ON cr.ID = crc.CR_ID
     JOIN CONTA_CONTABIL cc ON cc.ID = crc.CONTA_ID
     LEFT JOIN CONTA_DRIVER cd ON cd.CONTA_ID = crc.CONTA_ID
     LEFT JOIN CONTA_DRIVER_EXCECAO ex ON ex.CR_ID = crc.CR_ID AND ex.CONTA_ID = crc.CONTA_ID AND ex.ATIVO = true
     LEFT JOIN DRIVERS dgen ON dgen.ID = cd.DRIVER_ID
     LEFT JOIN DRIVERS dexc ON dexc.ID = ex.DRIVER_ID
     WHERE crc.ATIVO = true AND COALESCE(ex.PACOTE_ID, cd.PACOTE_ID, ex.DRIVER_ID, cd.DRIVER_ID) = {{pkgId}}
     ORDER BY cr.CODIGO, cc.CODIGO`;
const PARES = `SELECT crc.CR_ID, crc.CONTA_ID FROM CR_CONTA crc
     LEFT JOIN CONTA_DRIVER cd ON cd.CONTA_ID = crc.CONTA_ID
     LEFT JOIN CONTA_DRIVER_EXCECAO ex ON ex.CR_ID = crc.CR_ID AND ex.CONTA_ID = crc.CONTA_ID AND ex.ATIVO = true
     WHERE crc.ATIVO = true AND COALESCE(ex.PACOTE_ID, cd.PACOTE_ID, ex.DRIVER_ID, cd.DRIVER_ID) = {{pkgId}}`;

const code = `SELECT
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',r.ID,'DRIVER_ID',r.DRIVER_ID,'CR_ID',r.CR_ID,'CONTA_ID',r.CONTA_ID,
     'CR_CODIGO',r.CR_CODIGO,'CR_NOME',r.CR_NOME,'CONTA_CODIGO',r.CONTA_CODIGO,'CONTA_NOME',r.CONTA_NOME,
     'MODELO_ID',r.MODELO_ID,'MODELO_NOME',r.MODELO_NOME)) FROM (${REGRAS}) r), JSON_ARRAY()) AS REGRAS,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('ID',ID,'CICLO_ID',CICLO_ID,'CONTA_ID',CONTA_ID,'CR_ID',CR_ID,'DRIVER_ID',DRIVER_ID,'MES',MES,'VALOR',VALOR))
     FROM ORCAMENTO_PACOTE WHERE DRIVER_ID = {{pkgId}} AND CICLO_ID = {{cicloId}}), JSON_ARRAY()) AS ORCAMENTO,
  (SELECT JSON_OBJECT('ID',ID,'TIPO_RATEIO',TIPO_RATEIO,'BASE_PROPORCIONAL',BASE_PROPORCIONAL) FROM RATEIO_CONFIG WHERE DRIVER_ID = {{pkgId}} ORDER BY ID DESC LIMIT 1) AS RATEIO,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('CR_ID',CR_ID,'PERCENTUAL',PERCENTUAL)) FROM RATEIO_CR
     WHERE RATEIO_CONFIG_ID = (SELECT ID FROM RATEIO_CONFIG WHERE DRIVER_ID = {{pkgId}} ORDER BY ID DESC LIMIT 1)), JSON_ARRAY()) AS RATEIO_CR,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('CONTA_ID',cid,'VALOR',v)) FROM (
     SELECT rc.CONTA_ID cid, SUM(rc.VALOR) v FROM REALIZADO_CONTABIL rc
     JOIN (${PARES}) reg ON reg.CR_ID = rc.CR_ID AND reg.CONTA_ID = rc.CONTA_ID
     WHERE rc.ANO = {{ano}} GROUP BY rc.CONTA_ID) x), JSON_ARRAY()) AS REALIZADO`;

await createServerFunctionMitra({ projectId, name: 'hotPkgDetalhe', type: 'SQL', code,
  description: 'Abrir driver em 1 ida: regras+orcamento+rateio+rateioCr+realizado como JSON. Params: pkgId, cicloId, ano(=ano-1).' });
const fns = (await listServerFunctionsMitra({ projectId })).result;
console.log('hotPkgDetalhe =>', fns.find(x=>x.name==='hotPkgDetalhe')?.id);

-- tipo: SQL | Por driver: linhas atuais do desenho + último snapshot publicado, para detectar alterações não publicadas
SELECT
  d.ID AS DRIVER_ID,
  COALESCE((SELECT JSON_ARRAYAGG(JSON_OBJECT('CODIGO',f.CODIGO,'TIPO',f.TIPO,'FORMULA',f.FORMULA,'CONTA_ID',f.CONTA_ID,'ESCONDER',f.ESCONDER,'NEGRITO',f.NEGRITO,'FORMATO',f.FORMATO,'GRANULARIDADE',f.GRANULARIDADE,'RATEIO_ID',f.RATEIO_ID,'ORDEM',f.ORDEM,'PREMISSA_NOME',f.PREMISSA_NOME)) FROM DRIVER_FORMULA f WHERE f.DRIVER_ID = d.ID), JSON_ARRAY()) AS LINHAS,
  (SELECT v.SNAPSHOT FROM DRIVER_VERSAO v WHERE v.DRIVER_ID = d.ID ORDER BY v.NUMERO DESC LIMIT 1) AS SNAPSHOT
FROM DRIVERS d
WHERE d.ATIVO = 'true'
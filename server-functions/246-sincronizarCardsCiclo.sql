-- tipo: SQL | Sincroniza os cards do workflow (ORCAMENTO_STATUS e PACOTE_STATUS) de TODOS os ciclos nao fechados com o mapeamento atual de gestores (GESTOR_CR / GESTOR_PACOTE). Idempotente. Remove cards PENDENTE/CONFIRMADO sem vinculo e cria os que faltam (um por ciclo x CR e ciclo x pacote). Cards SUBMETIDO/APROVADO/REPROVADO nao sao tocados. Chamar apos criar/vincular/transferir/desvincular gestor. Param: agora (YYYY-MM-DDTHH:mm:ss). Retorna CARDS_CR e CARDS_PACOTE.
DELETE os FROM ORCAMENTO_STATUS os
    JOIN CICLO c ON c.ID = os.CICLO_ID AND c.STATUS <> 'FECHADO'
    WHERE os.STATUS IN ('PENDENTE', 'CONFIRMADO')
      AND NOT EXISTS (SELECT 1 FROM GESTOR_CR gc
      JOIN GESTOR g ON g.ID = gc.GESTOR_ID AND g.ATIVO = 'true'
        WHERE gc.CR_ID = os.CR_ID AND gc.GESTOR_ID = os.GESTOR_ID);
DELETE ps FROM PACOTE_STATUS ps
    JOIN CICLO c ON c.ID = ps.CICLO_ID AND c.STATUS <> 'FECHADO'
    WHERE ps.STATUS IN ('PENDENTE', 'CONFIRMADO')
      AND NOT EXISTS (SELECT 1 FROM GESTOR_PACOTE gp
      JOIN GESTOR g ON g.ID = gp.GESTOR_ID AND g.ATIVO = 'true'
      JOIN DRIVERS d ON d.ID = gp.DRIVER_ID AND d.ATIVO = 'true' AND d.ESCOPO = 'PACOTE'
        WHERE gp.DRIVER_ID = ps.DRIVER_ID AND gp.GESTOR_ID = ps.GESTOR_ID);
INSERT INTO ORCAMENTO_STATUS (CICLO_ID, GESTOR_ID, CR_ID, STATUS, DRIVERS_CONFIRMADOS, ATUALIZADO_EM)
    SELECT c.ID, gc.GESTOR_ID, gc.CR_ID, 'PENDENTE', '', '{{agora}}'
    FROM CICLO c
    CROSS JOIN GESTOR_CR gc
    JOIN GESTOR g ON g.ID = gc.GESTOR_ID AND g.ATIVO = 'true'
    WHERE c.STATUS <> 'FECHADO'
      AND NOT EXISTS (SELECT 1 FROM ORCAMENTO_STATUS os
        WHERE os.CICLO_ID = c.ID AND os.CR_ID = gc.CR_ID);
INSERT INTO PACOTE_STATUS (CICLO_ID, DRIVER_ID, GESTOR_ID, STATUS, ATUALIZADO_EM)
    SELECT c.ID, gp.DRIVER_ID, gp.GESTOR_ID, 'PENDENTE', '{{agora}}'
    FROM CICLO c
    CROSS JOIN GESTOR_PACOTE gp
    JOIN GESTOR g ON g.ID = gp.GESTOR_ID AND g.ATIVO = 'true'
    JOIN DRIVERS d ON d.ID = gp.DRIVER_ID AND d.ATIVO = 'true' AND d.ESCOPO = 'PACOTE'
    WHERE c.STATUS <> 'FECHADO'
      AND NOT EXISTS (SELECT 1 FROM PACOTE_STATUS ps
        WHERE ps.CICLO_ID = c.ID AND ps.DRIVER_ID = gp.DRIVER_ID);
SELECT
      (SELECT COUNT(*) FROM ORCAMENTO_STATUS os JOIN CICLO c ON c.ID = os.CICLO_ID WHERE c.STATUS <> 'FECHADO') AS CARDS_CR,
      (SELECT COUNT(*) FROM PACOTE_STATUS ps JOIN CICLO c ON c.ID = ps.CICLO_ID WHERE c.STATUS <> 'FECHADO') AS CARDS_PACOTE;
-- tipo: SQL | Total de modelos NORMAL por pacote do ciclo — snapshot TOTAL_MODELOS so quando a versao esta FECHADA, senao contagem ao vivo. Params: cicloId
SELECT ps.DRIVER_ID AS PACOTE_ID, COALESCE(MAX(CASE WHEN c.STATUS = 'FECHADO' THEN ps.TOTAL_MODELOS END), MAX(live.TOTAL), 0) AS TOTAL
FROM PACOTE_STATUS ps
JOIN CICLO c ON c.ID = ps.CICLO_ID
LEFT JOIN (SELECT COALESCE(cde.PACOTE_ID, cd.PACOTE_ID, cde.DRIVER_ID, cd.DRIVER_ID) AS PACOTE_ID,
       COUNT(DISTINCT modelo.ID) AS TOTAL
  FROM CR_CONTA crc
  LEFT JOIN CONTA_DRIVER_EXCECAO cde ON cde.CR_ID = crc.CR_ID AND cde.CONTA_ID = crc.CONTA_ID AND cde.ATIVO = true
  LEFT JOIN CONTA_DRIVER cd ON cd.CONTA_ID = crc.CONTA_ID
  LEFT JOIN DRIVERS modelo ON modelo.ID = COALESCE(cde.DRIVER_ID, cd.DRIVER_ID) AND modelo.TIPO_DRIVER = 'NORMAL'
  WHERE crc.ATIVO = true AND modelo.ID IS NOT NULL
  GROUP BY COALESCE(cde.PACOTE_ID, cd.PACOTE_ID, cde.DRIVER_ID, cd.DRIVER_ID)) live ON live.PACOTE_ID = ps.DRIVER_ID
WHERE ps.CICLO_ID = {{cicloId}}
GROUP BY ps.DRIVER_ID